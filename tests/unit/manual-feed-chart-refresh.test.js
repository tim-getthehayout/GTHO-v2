const flush = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
let event, dashboard, rendered, queued;
beforeEach(async () => {
  vi.useFakeTimers({ toFake: ['Date'] }); vi.setSystemTime(new Date('2026-11-10T12:00:00-05:00'));
  resetForms(); setActiveFarm(FARM);
  event = seed('events', EventEntity, { id: 'event', farmId: FARM });
  seed('locations', Location, { id: 'pasture', farmId: FARM, name: 'Yard', type: 'confinement' });
  seed('eventPaddockWindows', Window, { eventId: event.id, locationId: 'pasture', dateOpened: '2026-11-05' });
  seed('groups', Group, { id: 'herd', name: 'Herd' });
  seed('animals', Animal, { id: 'cow', tagNum: 'C1' });
  seed('animalWeightRecords', Weight, { animalId: 'cow', weightKg: 500, source: 'manual', recordedAt: '2026-11-01T00:00:00' });
  seed('animalGroupMemberships', Membership, { animalId: 'cow', groupId: 'herd', dateJoined: '2026-11-01' });
  seed('eventGroupWindows', GroupWindow, { eventId: event.id, groupId: 'herd', dateJoined: '2026-11-05', headCount: 1, avgWeightKg: 500 });
  seed('batches', Batch, { id: 'hay', name: 'Hay', feedTypeId: 'type', unit: 'bale', quantity: 20, remaining: 8, weightPerUnitKg: 100, dmPct: 100 });
  seed('eventFeedEntries', Entry, { id: 'delivery', eventId: event.id, locationId: 'pasture', batchId: 'hay', date: '2026-11-05', time: '10:00', quantity: 12 });
  const opening = seed('eventFeedChecks', Check, { eventId: event.id, date: '2026-11-05', time: '09:00' });
  seed('eventFeedCheckItems', Item, { feedCheckId: opening.id, locationId: 'pasture', batchId: 'hay', remainingQuantity: 2.5 });
  await flush();
  rendered = vi.spyOn(Chart, 'renderDmiChart'); queued = queueSpy();
  dashboard = document.createElement('main'); document.body.append(dashboard); renderDashboard(dashboard);
  openEventDetailSheet(event, OP, FARM);
});
afterEach(() => { closeEventDetailSheet(); dashboard?.remove(); vi.restoreAllMocks(); vi.useRealTimers(); });
const latest = compact => rendered.mock.calls.filter(([, , options]) => !!options.compact === compact).at(-1)?.[0];
async function refreshed(work) {
  const detail = document.querySelector('[data-testid="detail-dmi-chart"]'), card = dashboard.querySelector('[data-testid="dashboard-card-grid"]');
  const oldDetail = detail.firstChild, oldCard = card.firstChild, count = rendered.mock.calls.length;
  work(); await flush(); expect(rendered.mock.calls.length).toBeGreaterThanOrEqual(count + 2);
  expect(detail.firstChild).not.toBe(oldDetail); expect(card.firstChild).not.toBe(oldCard);
  expect(latest(true).map(day => day.result)).toEqual(latest(false).map(day => day.result));
}
it('mounted charts refresh through real check Save, item-only Edit and Delete without reopening', async () => {
  expect(rendered.mock.calls).toHaveLength(2);
  openFeedCheckSheet(event, OP); const panel = document.querySelector('#feed-check-sheet-panel');
  fill(panel, 'input[type="date"]', '2026-11-09', 'change'); fill(panel, 'input[type="time"]', '13:00'); fill(panel, 'input[type="number"]', '7');
  await refreshed(() => button(panel, 'Save feed check').click());
  const check = getAll('eventFeedChecks').find(row => row.date === '2026-11-09'), item = getAll('eventFeedCheckItems').find(row => row.feedCheckId === check.id);
  expect(queued('event_feed_checks').at(-1)).toMatchObject({ date: '2026-11-09', time: '13:00' });
  expect(latest(true)[0].result).toMatchObject({ status: 'actual', storedDmiKg: 187.5 });
  openEditFeedCheckDialog(check, item, event, OP); let edit = document.querySelector('#edit-fc-panel');
  fill(edit, 'input[type="time"]', '13:00'); fill(edit, 'input[type="number"]', '6');
  await refreshed(() => button(edit, 'Save').click()); expect(latest(true)[0].result.storedDmiKg).toBe(212.5);
  openEditFeedCheckDialog(getById('eventFeedChecks', check.id), getById('eventFeedCheckItems', item.id), event, OP); edit = document.querySelector('#edit-fc-panel');
  vi.spyOn(window, 'confirm').mockReturnValue(true); await refreshed(() => button(edit, 'Delete').click());
  expect(getById('eventFeedChecks', check.id)).toBeUndefined(); expect(latest(true)[0].result.storedDmiKg).toBe(12.5);
});
it('remote header/item and delivery changes redraw both charts; teardown and repeated mounts do not duplicate subscriptions', async () => {
  let check, item;
  await refreshed(() => { check = Check.create({ operationId: OP, eventId: event.id, date: '2026-11-09', time: '13:00' }); mergeRemote('eventFeedChecks', [check]); });
  await refreshed(() => { item = Item.create({ operationId: OP, feedCheckId: check.id, batchId: 'hay', locationId: 'pasture', remainingQuantity: 7 }); mergeRemote('eventFeedCheckItems', [item]); });
  expect(latest(true)[0].result.storedDmiKg).toBe(187.5);
  await refreshed(() => mergeRemote('eventFeedCheckItems', [{ ...item, remainingQuantity: 6, updatedAt: new Date().toISOString() }]));
  expect(latest(true)[0].result.storedDmiKg).toBe(212.5);
  await refreshed(() => update('eventFeedEntries', 'delivery', { time: '08:59' }, Entry.validate, Entry.toSupabaseShape, 'event_feed_entries'));
  expect(latest(true)[0].result.storedDmiKg).toBe(0);
  renderDashboard(dashboard); openEventDetailSheet(event, OP, FARM); const count = rendered.mock.calls.length;
  update('eventFeedCheckItems', item.id, { remainingQuantity: 5 }, Item.validate, Item.toSupabaseShape, 'event_feed_check_items');
  await flush(); expect(rendered.mock.calls).toHaveLength(count + 2);
  closeEventDetailSheet(); dashboard.remove(); const closed = rendered.mock.calls.length;
  mergeRemote('eventFeedCheckItems', [{ ...item, remainingQuantity: 4, updatedAt: new Date().toISOString() }]);
  await flush(); expect(rendered.mock.calls).toHaveLength(closed);
});

it('the mounted inline delivery clock editor refreshes DMI without touching inventory or a focused draft on check refresh', async () => {
  const closing = seed('eventFeedChecks', Check, { eventId: event.id, date: '2026-11-09', time: '13:00' });
  const item = seed('eventFeedCheckItems', Item, { feedCheckId: closing.id, locationId: 'pasture', batchId: 'hay', remainingQuantity: 7 });
  await flush(); expect(latest(true)[0].result.storedDmiKg).toBe(187.5);
  button(document.querySelector('[data-testid="detail-feed-entries"]'), 'Edit').click();
  const form = document.querySelector('[data-testid="feed-entry-inline-form"]'), clock = form.querySelector('input[type="time"]');
  expect(clock.value).toBe('10:00'); fill(form, 'input[type="time"]', '08:59'); clock.focus();
  await refreshed(() => update('eventFeedCheckItems', item.id, { remainingQuantity: 6 }, Item.validate, Item.toSupabaseShape, 'event_feed_check_items'));
  expect(document.activeElement).toBe(clock); expect(clock.value).toBe('08:59'); expect(clock.isConnected).toBe(true);
  const inventory = JSON.stringify({ batch: getById('batches', 'hay'), balances: getAll('batchLocationBalances') });
  await refreshed(() => button(form, 'Save changes').click()); expect(latest(true)[0].result.storedDmiKg).toBe(0);
  expect(getById('eventFeedEntries', 'delivery').time).toBe('08:59'); expect(queued('event_feed_entries').at(-1).time).toBe('08:59');
  expect(JSON.stringify({ batch: getById('batches', 'hay'), balances: getAll('batchLocationBalances') })).toBe(inventory);
  dashboard.remove(); document.querySelector('[data-testid="event-detail-view"]').remove(); const count = rendered.mock.calls.length;
  update('eventFeedEntries', 'delivery', { time: '09:01' }, Entry.validate, Entry.toSupabaseShape, 'event_feed_entries'); await flush();
  expect(rendered.mock.calls).toHaveLength(count);
});
